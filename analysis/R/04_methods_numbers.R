# Numbers quoted in the Methods section, written as LaTeX macros to out/methods_numbers.tex
# (main.tex \input's it before methods_draft.tex). Rerun after any change to the data or cleaning.

source(here::here("analysis", "R", "00_load_and_clean.R"))

# from Kieskompas's "Methodologische toelichting" (22-10-2026): panel members invited
n_invited <- 4284

raw <- haven::read_sav(here::here("analysis", "data", "NLOZ26-10_Drugsbeleid_gedeeld_261022.sav"))
broke_off <- read_csv(here::here("analysis", "data", "NLOZ26-10_Drugsbeleid_in progress_gedeeld_261022.csv"),
                      show_col_types = FALSE)

dates <- as.Date(raw$InterviewStartDate)
n_eff <- sum(df$w)^2 / sum(df$w^2)                         # Kish effective sample size
no_opinion <- \(prefix) colMeans(is.na(select(df, starts_with(prefix)))) * 100

macros <- list(
  rVersion      = paste(R.version$major, R.version$minor, sep = "."),
  nInvited      = n_invited,
  nStarted      = nrow(raw) + nrow(broke_off),
  nCompleted    = nrow(raw),
  nBrokeOff     = nrow(broke_off),
  nAnalytic     = nrow(df),
  responseRate  = round(100 * nrow(raw) / n_invited),
  fieldStart    = as.integer(format(min(dates), "%d")),
  fieldEnd      = paste(as.integer(format(max(dates), "%d")), month.name[as.integer(format(max(dates), "%m"))],
                        format(max(dates), "%Y")),   # month.name: English whatever the locale
  medianMinutes = round(median(raw$InterviewDuration) / 60, 1),
  nEff          = round(n_eff),
  designEffect  = round(nrow(df) / n_eff, 2),
  marginError   = round(100 * qnorm(0.975) * sqrt(0.25 / n_eff), 1),
  noOpPolicyMin = round(min(no_opinion("beleid_voorkeur_")), 1),
  noOpPolicyMax = round(max(no_opinion("beleid_voorkeur_")), 1),
  noOpBeliefMax = round(max(no_opinion("beliefs_")), 1)
)

writeLines(c("% generated by analysis/R/04_methods_numbers.R -- do not edit by hand",
             sprintf("\\newcommand{\\%s}{%s}", names(macros), map_chr(macros, \(x) format(x, big.mark = "{,}")))),
           here::here("out", "methods_numbers.tex"))
